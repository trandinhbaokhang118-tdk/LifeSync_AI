const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync(require('node:path').join(__dirname, '../src/lib/planner-scheduling.ts'), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const exportsObject = {};
vm.runInNewContext(output, { exports: exportsObject, Date, Number, String });
const { moveTaskToDay, localDayKey } = exportsObject;
const task = { startAt: new Date(2026, 8, 28, 15).toISOString(), dueAt: new Date(2026, 8, 28, 16).toISOString() };
const now = new Date(2026, 8, 29, 8);
const moved = moveTaskToDay(task, new Date(2026, 8, 29), now);
assert.equal(localDayKey(moved.start), '2026-09-29');
assert.equal(moved.start.getHours(), 15);
assert.equal(+moved.end - +moved.start, 3600000);
assert.ok(moveTaskToDay(task, new Date(2026, 8, 28), now).error);
assert.ok(moveTaskToDay(task, new Date(2026, 8, 29), new Date(2026, 8, 29, 16)).error);
assert.equal(localDayKey(moveTaskToDay(task, new Date(2026, 9, 1), now).start), '2026-10-01');
console.log(`Planner date checks passed (${Intl.DateTimeFormat().resolvedOptions().timeZone})`);
